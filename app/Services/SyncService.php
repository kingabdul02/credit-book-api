<?php

declare(strict_types=1);

namespace App\Services;

use App\Enums\SyncAction;
use App\Enums\SyncStatus;
use App\Models\Contact;
use App\Models\Debt;
use App\Models\Reminder;
use App\Models\SyncQueue;
use App\Models\Transaction;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;

class SyncService
{
    /**
     * Entity model class mapping.
     */
    private const ENTITY_MAP = [
        'contact' => Contact::class,
        'debt' => Debt::class,
        'transaction' => Transaction::class,
        'reminder' => Reminder::class,
    ];

    /**
     * Push a batch of changes from the client to the server.
     *
     * Each change includes:
     * - entity_type: contact|debt|transaction|reminder
     * - action: CREATE|UPDATE|DELETE
     * - client_id: UUID generated by the client
     * - client_timestamp: when the client made the change
     * - payload: the full entity data
     */
    public function push(string $userId, array $changes): array
    {
        $results = [];

        DB::transaction(function () use ($userId, $changes, &$results) {
            foreach ($changes as $change) {
                $results[] = $this->processChange($userId, $change);
            }
        });

        // Update user's last synced timestamp
        \App\Models\User::where('id', $userId)->update([
            'last_synced_at' => now(),
        ]);

        return $results;
    }

    /**
     * Pull all changes since the client's last sync.
     */
    public function pull(string $userId, ?string $lastSyncedAt = null): array
    {
        $since = $lastSyncedAt ? Carbon::parse($lastSyncedAt) : Carbon::createFromTimestamp(0);

        $changes = [];

        // Pull contacts
        $contacts = Contact::forUser($userId)
            ->withTrashed()
            ->where('updated_at', '>', $since)
            ->get();

        foreach ($contacts as $contact) {
            $changes[] = [
                'entity_type' => 'contact',
                'action' => $contact->trashed() ? SyncAction::DELETE->value : SyncAction::UPDATE->value,
                'client_id' => $contact->client_id,
                'server_timestamp' => $contact->updated_at?->toISOString(),
                'payload' => $contact->toArray(),
            ];
        }

        // Pull debts
        $debts = Debt::forUser($userId)
            ->withTrashed()
            ->where('updated_at', '>', $since)
            ->get();

        foreach ($debts as $debt) {
            $changes[] = [
                'entity_type' => 'debt',
                'action' => $debt->trashed() ? SyncAction::DELETE->value : SyncAction::UPDATE->value,
                'client_id' => $debt->client_id,
                'server_timestamp' => $debt->updated_at?->toISOString(),
                'payload' => $debt->toArray(),
            ];
        }

        // Pull transactions (no soft deletes — only new ones)
        $transactions = Transaction::forUser($userId)
            ->where('created_at', '>', $since)
            ->get();

        foreach ($transactions as $transaction) {
            $changes[] = [
                'entity_type' => 'transaction',
                'action' => SyncAction::CREATE->value,
                'client_id' => $transaction->client_id,
                'server_timestamp' => $transaction->created_at?->toISOString(),
                'payload' => $transaction->toArray(),
            ];
        }

        // Pull reminders
        $reminders = Reminder::forUser($userId)
            ->where('updated_at', '>', $since)
            ->get();

        foreach ($reminders as $reminder) {
            $changes[] = [
                'entity_type' => 'reminder',
                'action' => SyncAction::UPDATE->value,
                'client_id' => $reminder->client_id,
                'server_timestamp' => $reminder->updated_at?->toISOString(),
                'payload' => $reminder->toArray(),
            ];
        }

        return [
            'changes' => $changes,
            'server_timestamp' => now()?->toISOString(),
        ];
    }

    /**
     * Get sync status for a user.
     */
    public function getStatus(string $userId): array
    {
        return [
            'pending_count' => SyncQueue::forUser($userId)->pending()->count(),
            'conflict_count' => SyncQueue::forUser($userId)->conflicts()->count(),
            'conflicts' => SyncQueue::forUser($userId)->conflicts()->get(),
            'last_synced_at' => \App\Models\User::find($userId)?->last_synced_at?->toISOString(),
        ];
    }

    /**
     * Resolve a sync conflict by choosing client or server version.
     */
    public function resolveConflict(string $syncQueueId, string $userId, string $resolution): array
    {
        $syncEntry = SyncQueue::forUser($userId)->findOrFail($syncQueueId);

        if ($syncEntry->status !== SyncStatus::CONFLICT) {
            return ['error' => 'This entry is not in conflict status.'];
        }

        if ($resolution === 'client') {
            // Apply the client's version
            $this->applyChange(
                $userId,
                $syncEntry->entity_type,
                $syncEntry->action,
                $syncEntry->payload,
            );
        }
        // If resolution is 'server', we keep the server version (do nothing)

        $syncEntry->update([
            'status' => SyncStatus::PROCESSED,
            'server_timestamp' => now(),
        ]);

        return ['status' => 'resolved', 'resolution' => $resolution];
    }

    /**
     * Process a single change from the client.
     */
    private function processChange(string $userId, array $change): array
    {
        $entityType = $change['entity_type'];
        $action = SyncAction::from($change['action']);
        $clientId = $change['client_id'];
        $clientTimestamp = Carbon::parse($change['client_timestamp']);
        $payload = $change['payload'];

        // Check for existing entity by client_id (idempotency)
        $modelClass = self::ENTITY_MAP[$entityType] ?? null;

        if (! $modelClass) {
            return [
                'client_id' => $clientId,
                'status' => 'failed',
                'error' => "Unknown entity type: {$entityType}",
            ];
        }

        // Check if already processed (idempotency)
        $existing = $modelClass::where('client_id', $clientId)->first();

        if ($action === SyncAction::CREATE && $existing) {
            // Already exists — idempotent, skip
            return [
                'client_id' => $clientId,
                'status' => 'skipped',
                'message' => 'Entity already exists.',
            ];
        }

        if ($action === SyncAction::CREATE) {
            $this->applyChange($userId, $entityType, $action, $payload);

            // Log to sync queue
            SyncQueue::create([
                'user_id' => $userId,
                'entity_type' => $entityType,
                'entity_id' => $clientId,
                'action' => $action,
                'payload' => $payload,
                'client_timestamp' => $clientTimestamp,
                'server_timestamp' => now(),
                'status' => SyncStatus::PROCESSED,
            ]);

            return [
                'client_id' => $clientId,
                'status' => 'processed',
            ];
        }

        // UPDATE or DELETE — check for conflicts
        if ($existing && $existing->updated_at > $clientTimestamp) {
            // Server has a newer version — conflict
            SyncQueue::create([
                'user_id' => $userId,
                'entity_type' => $entityType,
                'entity_id' => $clientId,
                'action' => $action,
                'payload' => $payload,
                'client_timestamp' => $clientTimestamp,
                'server_timestamp' => now(),
                'status' => SyncStatus::CONFLICT,
                'conflict_data' => $existing->toArray(),
            ]);

            return [
                'client_id' => $clientId,
                'status' => 'conflict',
                'server_version' => $existing->toArray(),
            ];
        }

        // No conflict — apply the change
        $this->applyChange($userId, $entityType, $action, $payload);

        SyncQueue::create([
            'user_id' => $userId,
            'entity_type' => $entityType,
            'entity_id' => $clientId,
            'action' => $action,
            'payload' => $payload,
            'client_timestamp' => $clientTimestamp,
            'server_timestamp' => now(),
            'status' => SyncStatus::PROCESSED,
        ]);

        return [
            'client_id' => $clientId,
            'status' => 'processed',
        ];
    }

    /**
     * Apply a change to the database.
     */
    private function applyChange(string $userId, string $entityType, SyncAction $action, array $payload): void
    {
        $modelClass = self::ENTITY_MAP[$entityType];

        switch ($action) {
            case SyncAction::CREATE:
                $payload['user_id'] = $userId;
                $modelClass::create($payload);
                break;

            case SyncAction::UPDATE:
                $entity = $modelClass::where('client_id', $payload['client_id'])->first();
                if ($entity) {
                    unset($payload['id'], $payload['user_id'], $payload['created_at']);
                    $entity->update($payload);
                }
                break;

            case SyncAction::DELETE:
                $entity = $modelClass::where('client_id', $payload['client_id'])->first();
                $entity?->delete();
                break;
        }
    }
}
